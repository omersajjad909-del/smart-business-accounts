/**
 * Light-theme text colours for admin values that cannot be turned into CSS
 * variables in the source.
 *
 * theme-codemod.cjs rewrites literal colours into var(--tx-…). That is
 * impossible where a colour map is also used as `${colour}18` (hex + alpha for a
 * tinted background) or in SVG attributes, so those maps keep pale hex values —
 * #fbbf24 amber, #a5b4fc lilac — that are unreadable on a white page.
 *
 * For every such hex found under app/admin this writes one rule that darkens an
 * element's *inline text colour* when the page is light, same hue, 4.5:1 on
 * white. Only `color` is matched (not border-color / background-color), and
 * only inside .fin-admin-root, so nothing outside the console is touched. Dark
 * mode never matches `html:not(.dark)`.
 *
 * Usage: node scripts/theme-admin-inline.cjs   (re-run after adding colours)
 */
const fs = require("fs");
const path = require("path");

const ROOT = path.join(__dirname, "..");
const OUT = path.join(ROOT, "app/admin/admin-light-text.css");

function walk(dir, out) {
  for (const ent of fs.readdirSync(dir, { withFileTypes: true })) {
    const p = path.join(dir, ent.name);
    if (ent.isDirectory()) walk(p, out);
    else if (/\.tsx?$/.test(ent.name) && !p.endsWith("AdminShell.tsx")) out.push(p);
  }
  return out;
}

const rgbOf = (h) => [0, 2, 4].map((i) => parseInt(h.slice(i, i + 2), 16));
const f = (v) => { v /= 255; return v <= 0.03928 ? v / 12.92 : Math.pow((v + 0.055) / 1.055, 2.4); };
const lum = ([r, g, b]) => 0.2126 * f(r) + 0.7152 * f(g) + 0.0722 * f(b);
function toHsl([r, g, b]) {
  r /= 255; g /= 255; b /= 255;
  const max = Math.max(r, g, b), min = Math.min(r, g, b), l = (max + min) / 2;
  if (max === min) return [0, 0, l];
  const d = max - min, s = l > 0.5 ? d / (2 - max - min) : d / (max + min);
  const h = max === r ? (g - b) / d + (g < b ? 6 : 0) : max === g ? (b - r) / d + 2 : (r - g) / d + 4;
  return [h / 6, s, l];
}
function fromHsl([h, s, l]) {
  if (s === 0) return [l, l, l].map((v) => Math.round(v * 255));
  const q = l < 0.5 ? l * (1 + s) : l + s - l * s, p = 2 * l - q;
  const t = (x) => { if (x < 0) x += 1; if (x > 1) x -= 1; return x < 1 / 6 ? p + (q - p) * 6 * x : x < 1 / 2 ? q : x < 2 / 3 ? p + (q - p) * (2 / 3 - x) * 6 : p; };
  return [t(h + 1 / 3), t(h), t(h - 1 / 3)].map((v) => Math.round(v * 255));
}
// Same algorithm as forWhite() in theme-vars.cjs, so a colour looks the same
// whether it arrives through var(--tx-…) or through this file.
function forWhite(h) {
  const rgb0 = rgbOf(h);
  let [hh, s, l] = toHsl(rgb0);
  const chroma = (Math.max(...rgb0) - Math.min(...rgb0)) / 255;
  if (chroma < 0.12) { l = Math.min(0.42, Math.max(0.1, 1 - l)); s = Math.min(s, 0.2); }
  else {
    if (hh > 0.1 && hh < 0.17) { hh = 0.085; s = Math.max(s, 0.8); }
    l = Math.min(l, 0.45); s = Math.min(s, hh === 0.085 ? 0.85 : 0.65);
  }
  let rgb = fromHsl([hh, s, l]);
  while (1.05 / (lum(rgb) + 0.05) < 4.5 && l > 0.05) { l -= 0.01; rgb = fromHsl([hh, s, l]); }
  return rgb;
}
const hex = (rgb) => "#" + rgb.map((v) => v.toString(16).padStart(2, "0")).join("");

const found = new Set();
for (const file of walk(path.join(ROOT, "app/admin"), [])) {
  const src = fs.readFileSync(file, "utf8");
  for (const m of src.matchAll(/(?<![\w-])#([0-9a-fA-F]{6})\b(?![-\w])/g)) {
    // A fallback inside var(--tx-abc123, #abc123) is already handled.
    if (/var\(--[a-z]+-[0-9a-f]{6},\s*$/.test(src.slice(Math.max(0, m.index - 30), m.index))) continue;
    const h = m[1].toLowerCase();
    // Pale enough to be unreadable on white. Dark colours and white are fine.
    if (h !== "ffffff" && lum(rgbOf(h)) > 0.2 && 1.05 / (lum(rgbOf(h)) + 0.05) < 4.5) found.add(h);
  }
}

const rules = [...found].sort().map((h) => {
  const [r, g, b] = rgbOf(h);
  const dark = `rgb(${r}, ${g}, ${b})`;
  return `html:not(.dark) .fin-admin-root :is([style^="color: ${dark}"], [style*="; color: ${dark}"]){color:${hex(forWhite(h))} !important}`;
});

fs.writeFileSync(
  OUT,
  `/* GENERATED by scripts/theme-admin-inline.cjs — do not edit by hand.\n   Darkens pale inline text colours in the admin console when the page is light. */\n${rules.join("\n")}\n`,
);
console.log(`wrote ${rules.length} rules to ${path.relative(ROOT, OUT)}`);
